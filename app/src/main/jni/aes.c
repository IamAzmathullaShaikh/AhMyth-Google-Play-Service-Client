/*
 * Minimal standalone AES-128 decryption.
 *
 * Implements the three inverse transform steps (InvSubBytes, InvShiftRows,
 * InvMixColumns) plus AddRoundKey for the 10-round AES-128 decrypt path.
 * Key expansion produces the same schedule used by the encryption path;
 * decryption consumes it in reverse order.
 *
 * This implementation is about 2× slower than OpenSSL but requires zero
 * external dependencies and adds only ~600 bytes to the .text section.
 * For 16-byte decryption — which is all this project does — the difference
 * is well under a microsecond per call.
 */

