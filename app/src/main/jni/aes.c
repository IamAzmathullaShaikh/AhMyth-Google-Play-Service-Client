/* ================================================================
 * Rcon — round constants used during key expansion
 * ================================================================ */
static const uint8_t RCON[11] = {
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36
};

/* ================================================================
 * Helper: GF(2^8) multiplication by 2, 9, 11, 13, 14
 * Used by MixColumns (encrypt) and InvMixColumns (decrypt).
 * ================================================================ */
static uint8_t gf_mul2(uint8_t x) {
    return (x & 0x80) ? ((x << 1) ^ 0x1b) : (x << 1);
}

static uint8_t gf_mul3(uint8_t x) { return gf_mul2(x) ^ x; }

static uint8_t gf_mul9(uint8_t x)  { return gf_mul2(gf_mul2(gf_mul2(x))) ^ x; }
static uint8_t gf_mul11(uint8_t x) { return gf_mul2(gf_mul2(gf_mul2(x))) ^ gf_mul2(x) ^ x; }
static uint8_t gf_mul13(uint8_t x) { return gf_mul2(gf_mul2(gf_mul2(x))) ^ gf_mul2(gf_mul2(x)) ^ x; }
static uint8_t gf_mul14(uint8_t x) { return gf_mul2(gf_mul2(gf_mul2(x))) ^ gf_mul2(gf_mul2(x)) ^ gf_mul2(x); }

/* ================================================================
 * Key expansion: 16 bytes → 44 words (176 bytes)
 * ================================================================ */
void aes128_key_expand(const uint8_t key[16], uint32_t rk[44]) {
    int i;
    uint32_t temp;

    /* First 4 words = original key */
    for (i = 0; i < 4; i++) {
        rk[i] = ((uint32_t)key[4*i] << 24)
              | ((uint32_t)key[4*i+1] << 16)
              | ((uint32_t)key[4*i+2] << 8)
              | ((uint32_t)key[4*i+3]);
    }

    for (i = 4; i < 44; i++) {
        temp = rk[i-1];
        if ((i % 4) == 0) {
            /* RotWord */
            temp = (temp << 8) | (temp >> 24);
            /* SubWord */
            temp = ((uint32_t)SBOX[(temp >> 24) & 0xff] << 24)
                 | ((uint32_t)SBOX[(temp >> 16) & 0xff] << 16)
                 | ((uint32_t)SBOX[(temp >> 8) & 0xff] << 8)
                 | ((uint32_t)SBOX[temp & 0xff]);
            /* XOR with Rcon */
            temp ^= (uint32_t)RCON[i/4] << 24;
        }
        rk[i] = rk[i-4] ^ temp;
    }
}

/* ================================================================
 * AddRoundKey: XOR 16-byte block with round key word-by-word
 * ================================================================ */
void aes128_add_round_key(uint8_t block[16], const uint32_t rk[44], int round) {
    int i;
    for (i = 0; i < 4; i++) {
        uint32_t w = rk[round * 4 + i];
        block[4*i]     ^= (uint8_t)(w >> 24);
        block[4*i + 1] ^= (uint8_t)(w >> 16);
        block[4*i + 2] ^= (uint8_t)(w >> 8);
        block[4*i + 3] ^= (uint8_t)(w);
    }
}

/* ================================================================
 * InvSubBytes: byte-wise substitution using inverse S-box
 * ================================================================ */
static void inv_sub_bytes(uint8_t block[16]) {
    int i;
    for (i = 0; i < 16; i++) {
        block[i] = INV_SBOX[block[i]];
    }
}

/* ================================================================
 * InvShiftRows: rotate rows right
 *   Row 0: no shift
 *   Row 1: shift right by 1
 *   Row 2: shift right by 2
 *   Row 3: shift right by 3
 * ================================================================ */
static void inv_shift_rows(uint8_t block[16]) {
    uint8_t tmp;

    /* Row 1: shift right by 1 */
    tmp = block[13];
    block[13] = block[9];
    block[9]  = block[5];
    block[5]  = block[1];
    block[1]  = tmp;

    /* Row 2: shift right by 2 */
    tmp = block[2];  block[2] = block[10]; block[10] = tmp;
    tmp = block[6];  block[6] = block[14]; block[14] = tmp;

    /* Row 3: shift right by 3 */
    tmp = block[3];
    block[3]  = block[7];
    block[7]  = block[11];
    block[11] = block[15];
    block[15] = tmp;
}

/* ================================================================
 * InvMixColumns: column-wise GF(2^8) matrix multiply
 * Each column c = (a0,a1,a2,a3) becomes:
 *   b0 = (14*a0) ^ (11*a1) ^ (13*a2) ^ (9*a3)
 *   b1 = (9*a0)  ^ (14*a1) ^ (11*a2) ^ (13*a3)
 *   b2 = (13*a0) ^ (9*a1)  ^ (14*a2) ^ (11*a3)
 *   b3 = (11*a0) ^ (13*a1) ^ (9*a2)  ^ (14*a3)
 * ================================================================ */
static void inv_mix_columns(uint8_t block[16]) {
    int c;
    for (c = 0; c < 4; c++) {
        int i = c * 4;
        uint8_t a0 = block[i];
        uint8_t a1 = block[i+1];
        uint8_t a2 = block[i+2];
        uint8_t a3 = block[i+3];

        block[i]   = gf_mul14(a0) ^ gf_mul11(a1) ^ gf_mul13(a2) ^ gf_mul9(a3);
        block[i+1] = gf_mul9(a0)  ^ gf_mul14(a1) ^ gf_mul11(a2) ^ gf_mul13(a3);
        block[i+2] = gf_mul13(a0) ^ gf_mul9(a1)  ^ gf_mul14(a2) ^ gf_mul11(a3);
        block[i+3] = gf_mul11(a0) ^ gf_mul13(a1) ^ gf_mul9(a2)  ^ gf_mul14(a3);
    }
}

/* ================================================================
 * AES-128 decrypt block
 *
 * Decrypt path:
 *   1. AddRoundKey (round 10 key)
 *   2. Round 9..1: InvShiftRows → InvSubBytes → AddRoundKey → InvMixColumns
 *   3. Round 0:    InvShiftRows → InvSubBytes → AddRoundKey
 * ================================================================ */
void aes128_decrypt_block(uint8_t block[16], const uint32_t rk[44]) {
    int round;

    /* Initial AddRoundKey (round 10) */
    aes128_add_round_key(block, rk, 10);

    /* Rounds 9 down to 1 */
    for (round = 9; round >= 1; round--) {
        inv_shift_rows(block);
        inv_sub_bytes(block);
        aes128_add_round_key(block, rk, round);
        inv_mix_columns(block);
    }

    /* Final round (round 0) — no InvMixColumns */
    inv_shift_rows(block);
    inv_sub_bytes(block);
    aes128_add_round_key(block, rk, 0);
}
